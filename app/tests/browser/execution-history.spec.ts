import {test,expect} from "@playwright/test";
test("execution history opens at latest in a bounded viewport, loads older without jumping, preserves reading on updates and collapses locally",async({page})=>{
 let count=20,writes=0;page.on('request',r=>{if(r.method()==='POST')writes++;});
 await page.route('**/api/snapshot',async route=>{
   const s=await(await route.fetch()).json();
   s.tasks=[{id:'scroll-task',title:'执行历史滚动验收',objective:'独立UI夹具',owner:'developer',status:'running',executor:'dsh',purpose:'product',acceptance:'autonomous',evidence:[],runs:[],messages:[]}];
   s.messages=[];s.runs=[];s.deliveries=[];s.annotations=[];
   s.executions=Array.from({length:count},(_,i)=>({id:`scroll-${i}`,taskId:'scroll-task',status:'finished_unverified',createdAt:new Date(Date.UTC(2026,9,24,0,i)).toISOString(),startedAt:new Date(Date.UTC(2026,9,24,0,i)).toISOString(),updatedAt:new Date(Date.UTC(2026,9,24,0,i)).toISOString(),lastActivityAt:new Date(Date.UTC(2026,9,24,0,i)).toISOString()})).reverse();
   await route.fulfill({json:s});
 });
 await page.goto('/');await page.getByRole('button',{name:'任务',exact:true}).click();
 const task=page.locator('[data-task-id="scroll-task"]');
 await task.getByRole('button',{name:'查看详情',exact:true}).click();
 const history=task.getByLabel('DSH 执行历史',{exact:true});
 await expect(history.locator('.execution-history-entry')).toHaveCount(0);
 await history.getByRole('button',{name:'展开执行记录',exact:true}).click();
 const box=history.getByRole('region',{name:'DSH 执行记录滚动区域',exact:true});
 await expect(history.locator('.execution-history-entry')).toHaveCount(5);
 await expect(history.locator('.execution-history-entry').last()).toHaveAttribute('data-execution-id','scroll-19');
 await expect.poll(()=>box.evaluate(e=>e.scrollHeight-e.scrollTop-e.clientHeight)).toBeLessThan(5);
 expect(await box.evaluate(e=>e.clientHeight)).toBeLessThanOrEqual(520);
 const anchor=await box.evaluate(e=>{e.scrollTop=0;return e.querySelector('[data-execution-id="scroll-15"]')!.getBoundingClientRect().top;});
 await expect(history.locator('.execution-history-entry')).toHaveCount(10);
 expect(Math.abs((await history.locator('[data-execution-id="scroll-15"]').boundingBox())!.y-anchor)).toBeLessThan(3);
 const before=await box.evaluate(e=>e.scrollTop);
 count=21;await page.getByRole('button',{name:'↻ 刷新',exact:true}).click();
 await expect(history.getByRole('button',{name:'有新记录，查看最新',exact:true})).toBeVisible();
 expect(Math.abs(await box.evaluate(e=>e.scrollTop)-before)).toBeLessThan(3);
 await history.getByRole('button',{name:'有新记录，查看最新',exact:true}).click();
 await expect(history.locator('.execution-history-entry')).toHaveCount(5);
 await expect(history.locator('.execution-history-entry').last()).toHaveAttribute('data-execution-id','scroll-20');
 await expect.poll(()=>box.evaluate(e=>e.scrollHeight-e.scrollTop-e.clientHeight)).toBeLessThan(5);
  count=22;await page.getByRole('button',{name:'↻ 刷新',exact:true}).click();
  await expect(history.locator('.execution-history-entry').last()).toHaveAttribute('data-execution-id','scroll-21');
  await expect.poll(()=>box.evaluate(e=>e.scrollHeight-e.scrollTop-e.clientHeight)).toBeLessThan(5);
 await history.getByRole('button',{name:'收起执行记录',exact:true}).click();
 await expect(box).toHaveCount(0);await expect(task.locator('.task-expanded')).toBeVisible();
 await history.getByRole('button',{name:'展开执行记录',exact:true}).click();
 await expect(history.locator('.execution-history-entry')).toHaveCount(5);
 await expect.poll(()=>history.getByRole('region').evaluate(e=>e.scrollHeight-e.scrollTop-e.clientHeight)).toBeLessThan(5);
 expect(writes).toBe(0);
});
