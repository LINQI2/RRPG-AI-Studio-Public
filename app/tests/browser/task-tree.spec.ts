import {test,expect} from "@playwright/test";
import {openTaskRegistration} from "./task-navigation.js";
test("producer can register a child and detach it without dispatching execution; relationship survives refresh",async({page})=>{
 await page.goto('/');
 const {csrf}=await(await page.request.get('/api/session')).json();
 const parent=await(await page.request.post('/api/tasks',{headers:{'x-studio-csrf':csrf},data:{title:'树归属验收父任务',objective:'纯协议测试，不触发模型',owner:'developer',acceptance:'autonomous'}})).json();
 await page.getByRole('button',{name:'任务',exact:true}).click();
 await openTaskRegistration(page);
 await page.getByLabel('任务标题').fill('树归属验收子任务');
 await page.getByLabel('任务目标').fill('独立子范围');
 await page.getByLabel('上级任务',{exact:true}).selectOption(parent.id);
 await page.getByRole('button',{name:'登记任务',exact:true}).click();
 const p=page.locator(`[data-task-id="${parent.id}"]`);
 await p.getByRole('button',{name:'展开子任务（1）',exact:true}).click();
 const child=page.locator('.task-card').filter({has:page.locator('.task-summary-title',{hasText:'树归属验收子任务'})});
 await child.getByRole('button',{name:'查看详情',exact:true}).click();
 await child.getByRole('button',{name:'调整任务归属',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'调整任务归属'});
 await dialog.getByLabel('上级任务',{exact:true}).selectOption('__root__');
 await dialog.getByLabel('归属依据').fill('经核对这是独立工作目标，取消父子关联；不改变执行状态');
 await dialog.getByRole('button',{name:'确认提交',exact:true}).click();
 await dialog.getByRole('button',{name:'关闭',exact:true}).click();
 await page.reload();
 await expect(child).toContainText('顶层任务');
 await expect(child).toContainText('待安排');
 await expect(p.getByRole('button',{name:/展开子任务/})).toHaveCount(0);
});
test("tree branches and task details expand independently, keep filtered ancestry and aggregate child activity",async({page})=>{
 let writes=0;page.on("request",r=>{if(r.method()==="POST")writes++;});
 await page.route("**/api/snapshot",async route=>{
   const data=await(await route.fetch()).json();
   const base={owner:"developer",executor:"codex",status:"pending",acceptance:"autonomous",purpose:"product",evidence:[],messages:[],runs:[],createdAt:"2026-10-22T01:00:00Z",updatedAt:"2026-10-22T02:00:00Z"};
   data.tasks=[{...base,id:"parent",title:"研发总目标",objective:"父任务完整要求"},{...base,id:"child",title:"实现工作包",objective:"子任务要求",parentTaskId:"parent"},{...base,id:"sibling",title:"验证工作包",objective:"同级验证",parentTaskId:"parent"},{...base,id:"grandchild",title:"专项测试",objective:"下级测试",parentTaskId:"child"}];
   data.executions=[{id:"real-fixture-event",taskId:"child",status:"running",lastActivityAt:"2026-10-24T05:08:09Z"}];
   data.messages=[];data.deliveries=[];data.annotations=[];data.runs=[];data.dsh={...data.dsh,maintenance:false};
   await route.fulfill({json:data});
 });
 await page.goto("/");await page.getByRole("button",{name:"任务",exact:true}).click();
 const root=page.locator('[data-task-id="parent"]');
 await expect(page.locator('.task-card')).toHaveCount(1);
 await expect(root.getByLabel('子任务概况')).toContainText('直属子任务 2 个 · 全部下级 3 个 · 本任务及下级活跃执行 1 个');
 await expect(root.getByLabel('子任务概况').locator('time')).toHaveAttribute('datetime','2026-10-24T05:08:09.000Z');
 await root.locator('.task-summary-title').click();
 await expect(root.locator('.task-expanded')).toHaveCount(0);
 await root.getByRole('button',{name:'展开子任务（2）',exact:true}).click();
 await expect(page.locator('.task-card')).toHaveCount(3);
 await expect(root.locator('.task-expanded')).toHaveCount(0);
 await root.getByRole('button',{name:'查看详情',exact:true}).click();
 await expect(root.locator('.task-expanded')).toBeVisible();
 await expect(page.locator('[data-task-id="child"]')).toBeVisible();
 await root.getByRole('button',{name:'收起详情',exact:true}).click();
 await expect(page.locator('[data-task-id="child"]')).toBeVisible();
 await page.locator('[data-task-id="child"]').getByRole('button',{name:'展开子任务（1）',exact:true}).click();
 await expect(page.locator('[data-task-id="grandchild"]')).toBeVisible();
 await root.getByRole('button',{name:'收起子任务（2）',exact:true}).click();
 await expect(page.locator('.task-card')).toHaveCount(1);
 await page.getByPlaceholder('筛选标题 / 状态 / 负责人').fill('专项测试');
 // Filter retains the path, even if a branch was explicitly collapsed earlier.
 await root.getByRole('button',{name:'展开子任务（2）',exact:true}).click();
 await expect(page.locator('[data-task-id="grandchild"]')).toBeVisible();
 await expect(page.locator('[data-task-id="sibling"]')).toHaveCount(0);
 expect(writes).toBe(0);
});
